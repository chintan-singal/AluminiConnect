test('gallery filters preserve dated captions and dialogs restore page scrolling',()=>{
  const view=render(h(PhotoGallery))
  expect(screen.getAllByRole('button',{name:/^View /})).toHaveLength(4)
  fireEvent.click(screen.getByRole('button',{name:'Campus',exact:true}))
  expect(screen.getAllByRole('button',{name:/^View /})).toHaveLength(1)
  fireEvent.click(screen.getByRole('button',{name:'View A home for South Asian scholarship'}))
  expect(document.body.style.overflow).toBe('hidden')
  fireEvent.click(screen.getByRole('button',{name:'Close dialog'}))
  expect(document.body.style.overflow).toBe('')
  fireEvent.click(screen.getByRole('button',{name:'Community',exact:true}))
  expect(screen.getByText(/Indian and Pakistani students/)).toBeTruthy()
  fireEvent.click(screen.getByRole('button',{name:'View Celebrating together'}))
  fireEvent(screen.getByRole('dialog'),new Event('cancel',{bubbles:true,cancelable:true}))
  expect(screen.queryByRole('dialog')).toBeNull()
  fireEvent.click(screen.getByRole('button',{name:'Archive',exact:true}))
  expect(screen.getAllByRole('button',{name:/^View /})).toHaveLength(2)
  fireEvent.click(screen.getByRole('button',{name:'View A campus imagined'}))
  fireEvent.click(screen.getByRole('dialog'))
  expect(screen.queryByRole('dialog')).toBeNull()
  view.unmount()
})
