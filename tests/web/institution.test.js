test('appearance applies and persists both themes',async()=>{
  localStorage.setItem('assembly-theme','light')
  render(h(ThemeProvider,null,h(Appearance)))
  expect(document.documentElement.dataset.theme).toBe('light')
  fireEvent.click(screen.getByRole('button',{name:'Dark',exact:true}))
  await waitFor(()=>expect(localStorage.getItem('assembly-theme')).toBe('dark'))
  expect(document.documentElement.dataset.theme).toBe('dark')
})
