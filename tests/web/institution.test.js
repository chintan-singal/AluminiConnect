test('directory passes location and field to the API and opens only returned profile data',async()=>{
  mock(()=>[member])
  const chat=jest.fn(),mentor=jest.fn()
  const view=render(h(People,{version:0,me:99,chat,mentor}))
  fireEvent.change(screen.getByLabelText('Location'),{target:{value:'Colombo'}})
  fireEvent.change(screen.getByLabelText('Professional field'),{target:{value:'Economics'}})
  await screen.findByRole('button',{name:/Message Test Graduate/})
  await waitFor(()=>expect(global.fetch.mock.calls.at(-1)[0]).toContain('city=Colombo&field=Economics'))
  fireEvent.click(screen.getByRole('button',{name:'View profile'}))
  expect(screen.getByRole('dialog',{name:member.name})).toBeTruthy()
  expect(screen.getByText('Graduation year')).toBeTruthy()
  fireEvent.click(screen.getAllByRole('button',{name:'View office hours'}).at(-1))
  expect(mentor).toHaveBeenCalledWith(7)
  view.unmount()
})
